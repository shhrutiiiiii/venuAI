#!/usr/bin/env python3
"""Print fresh random secrets for .env / .env.prod. Writes nothing; redirect deliberately:

    python scripts/security/gen_secrets.py >> .env.prod

Rotation: generate a new value, update the secret store/env file, restart. Rotating
JWT_SECRET_KEY invalidates all sessions (users log in again).
"""
import secrets


def main() -> None:
    print("# generated by scripts/security/gen_secrets.py - do not commit")
    print(f"JWT_SECRET_KEY={secrets.token_urlsafe(48)}")
    print(f"MCP_API_KEY={secrets.token_urlsafe(32)}")
    print(f"POSTGRES_PASSWORD={secrets.token_urlsafe(24)}")


if __name__ == "__main__":
    main()
